/**
 * Escapes HTML special characters to prevent XSS when interpolating
 * user-sourced values into HTML strings (e.g. document.write).
 */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
